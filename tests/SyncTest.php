<?php

declare(strict_types=1);

namespace Kodvalley\Improj\Tests;

use Kodvalley\Improj\Exception\ConfigurationException;
use Kodvalley\Improj\Exception\ErrorCode;
use Kodvalley\Improj\Exception\ImprojException;
use Kodvalley\Improj\Exception\MethodNotAllowedException;
use Kodvalley\Improj\Exception\NotFoundException;
use Kodvalley\Improj\Exception\PayloadTooLargeException;
use Kodvalley\Improj\Exception\ServerException;
use Kodvalley\Improj\Exception\ServiceUnavailableException;
use Kodvalley\Improj\Exception\UnsupportedMediaTypeException;
use Kodvalley\Improj\Model\AgentItem;
use Kodvalley\Improj\RequestOptions;
use Kodvalley\Improj\Tests\Support\MockClient;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * Behaviour added with the completed 2026-10-24 contract: documented error
 * codes and classes, X-Request-Id, per-request API version, typed agents and
 * the signed next_cursor.
 */
final class SyncTest extends TestCase
{
    /**
     * @return array<string, mixed>
     */
    public static function agentItem(int $id): array
    {
        return [
            'id' => $id, 'kind' => 'briefing', 'severity' => 'info', 'title' => "Item {$id}", 'body' => 'Text',
            'project' => ['id' => 42, 'name' => 'P'], 'citations' => [['label' => 'Task 7', 'path' => '/app/projects/42/tasks/7']],
            'aiGenerated' => true, 'notice' => 'Generated by AI.', 'status' => 'new', 'read' => false, 'createdAt' => '2026-10-24T09:00:00Z',
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private static function spec(): array
    {
        $spec = json_decode((string) file_get_contents(__DIR__ . '/fixtures/openapi.json'), true, 512, \JSON_THROW_ON_ERROR);
        self::assertIsArray($spec);

        /** @var array<string, mixed> $spec */
        return $spec;
    }

    public function testErrorCodeListsEveryCodeTheSpecNames(): void
    {
        $spec = self::spec();
        self::assertIsArray($spec['components']);
        self::assertIsArray($spec['components']['responses']);
        $named = [];
        foreach ($spec['components']['responses'] as $response) {
            self::assertIsArray($response);
            self::assertIsString($response['description']);
            preg_match_all('/\b[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+\b/', $response['description'], $m);
            foreach ($m[0] as $code) {
                $named[$code] = true;
            }
        }
        unset($named['X_REQUEST_ID']);
        self::assertGreaterThan(15, \count($named));
        self::assertSame([], array_values(array_diff(array_keys($named), ErrorCode::API_CODES)));
    }

    /**
     * @return iterable<string, array{int, string, class-string<ImprojException>}>
     */
    public static function newStatuses(): iterable
    {
        yield '405' => [405, ErrorCode::API_METHOD_NOT_ALLOWED, MethodNotAllowedException::class];
        yield '413' => [413, ErrorCode::FILE_TOO_LARGE_FOR_PLAN, PayloadTooLargeException::class];
        yield '415' => [415, ErrorCode::API_UNSUPPORTED_MEDIA_TYPE, UnsupportedMediaTypeException::class];
        yield '503' => [503, ErrorCode::SERVER_BUSY, ServiceUnavailableException::class];
    }

    /**
     * @param class-string<ImprojException> $class
     */
    #[DataProvider('newStatuses')]
    public function testNewStatusesHaveTheirOwnClass(int $status, string $code, string $class): void
    {
        $m = new MockClient(MockClient::problem($status, $code));
        try {
            $m->client(maxRetries: 0)->tasks->get(1, 2);
            self::fail('no exception');
        } catch (ImprojException $e) {
            self::assertInstanceOf($class, $e);
            self::assertSame($code, $e->getErrorCode());
            if ($status === 503) {
                self::assertInstanceOf(ServerException::class, $e);
            }
        }
    }

    public function testSendsYourRequestIdAndReportsTheEcho(): void
    {
        $m = new MockClient(MockClient::problem(404, 'NOT_FOUND', ['X-Request-Id' => 'sync-job-42:7']));
        try {
            $m->client()->tasks->get(1, 2, new RequestOptions(requestId: 'sync-job-42:7'));
            self::fail('no exception');
        } catch (NotFoundException $e) {
            self::assertSame('sync-job-42:7', $m->last()->getHeaderLine('X-Request-Id'));
            self::assertSame('sync-job-42:7', $e->getRequestId());
        }
    }

    public function testPerRequestApiVersion(): void
    {
        $m = new MockClient(MockClient::json(200, ['openapi' => '3.1.0']));
        $c = $m->client();
        $c->openapi(new RequestOptions(apiVersion: '2026-10-24'));
        self::assertSame('2026-10-24', $m->last()->getHeaderLine('IMPROJ-API-Version'));
        $c->openapi(new RequestOptions(apiVersion: false));
        self::assertFalse($m->last()->hasHeader('IMPROJ-API-Version'));
    }

    public function testValidatesTheNewOptionsAndHeaders(): void
    {
        $c = (new MockClient(MockClient::json(200, [])))->client();
        $bad = [
            new RequestOptions(requestId: 'short'),
            new RequestOptions(requestId: 'has space in it'),
            new RequestOptions(apiVersion: 'next'),
            new RequestOptions(headers: ['X-Request-Id' => 'abcdefgh']),
            new RequestOptions(headers: ['IMPROJ-API-Version' => '2026-10-24']),
            new RequestOptions(headers: ['Idempotency-Key' => 'k']),
        ];
        foreach ($bad as $options) {
            try {
                $c->openapi($options);
                self::fail('accepted');
            } catch (ConfigurationException) {
                self::addToAssertionCount(1);
            }
        }
    }

    public function testUploadPutKeepsRequestIdButNotTheIdempotencyKey(): void
    {
        $file = ['id' => 77, 'project_id' => 1, 'name' => 'a', 'type' => 'upload', 'is_folder' => false, 'parent_id' => null, 'mime_type' => null, 'size' => 3, 'visibility' => null, 'downloadable' => true, 'created_at' => null, 'updated_at' => null];
        $m = new MockClient(MockClient::json(201, ['data' => $file]));
        $m->client()->files->sendUpload('upl_ABCDEFGHIJKLMNOPQRSTUVWXYZ012345', 'abc', new RequestOptions(idempotencyKey: 'k1', requestId: 'upload-0001'));
        self::assertSame('upload-0001', $m->last()->getHeaderLine('X-Request-Id'));
        self::assertFalse($m->last()->hasHeader('Idempotency-Key'));
    }

    public function testTypedAgentsAndTheSignedCursor(): void
    {
        $m = new MockClient(
            MockClient::json(200, ['data' => [['id' => 4, 'name' => 'Ops agent', 'organization' => ['id' => 2, 'name' => 'Org'], 'status' => 'active', 'pausedReason' => null, 'principal' => true]]]),
            MockClient::json(200, ['data' => [self::agentItem(9)], 'next_cursor' => 'eyJ2IjoxfQ.c2ln', 'nextCursor' => 9]),
            MockClient::json(200, ['data' => [self::agentItem(8)], 'next_cursor' => null, 'nextCursor' => null]),
            MockClient::json(201, ['data' => ['id' => 5, 'status' => 'delivered']]),
        );
        $c = $m->client();
        $agents = $c->agents->list();
        self::assertSame('Org', $agents[0]->organization->name);
        self::assertTrue($agents[0]->principal);

        $items = iterator_to_array($c->agents->items(4)->autoPaging(), false);
        self::assertSame([9, 8], array_map(static fn(AgentItem $i): int => $i->id, $items));
        self::assertSame('cursor=eyJ2IjoxfQ.c2ln', $m->requests[2]->getUri()->getQuery());
        self::assertSame('/app/projects/42/tasks/7', $items[0]->citations[0]->path);
        self::assertTrue($items[0]->aiGenerated);
        self::assertSame(42, $items[0]->project?->id);

        $note = $c->agents->postNote(4, ['kind' => 'question', 'text' => 'Status?']);
        self::assertSame(5, $note->id);
        self::assertSame('delivered', $note->status);
    }
}
